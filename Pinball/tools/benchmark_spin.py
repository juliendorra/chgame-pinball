#!/usr/bin/env python3
"""Compare contact-spin models with the historical seeded-scatter reference.

Uses the shared game build, nine tables, identical seed cohorts, fixed button
tapes and reactive synthetic players from benchmark_scatter.py.
"""
import argparse
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
import os
from pathlib import Path
import re
import statistics as st
import subprocess

from benchmark_scatter import analyse, digest
from boards import encode
from build_studio import GAME, ROOT, WORK, SDK, VERSION, engine_inputs, inputs, node

BASELINE=GAME/'docs/spin-baseline.json'
CONFIGS={
    'current':dict(passive=4,powered=16,eject=8,grip=0,forget=0),
    'no_scatter':dict(passive=0,powered=0,eject=0,grip=0,forget=0),
    'spin_light':dict(passive=0,powered=0,eject=0,grip=16,forget=0),
    'spin':dict(passive=0,powered=0,eject=0,grip=32,forget=0),
    'spin_grippy':dict(passive=0,powered=0,eject=0,grip=64,forget=0),
    'hybrid':dict(passive=0,powered=16,eject=8,grip=32,forget=0),
    'spin_no_memory':dict(passive=0,powered=0,eject=0,grip=32,forget=1),
}
# Keep historical reference values fixed when the shipping defaults change.
# Explicit per-model flags below override the shared game configuration.

def flags_for(c):
    return [f'-DPINBALL_SCATTER_{k.upper()}={c[k]}' for k in ('passive','powered','eject')]+[
        f'-DPINBALL_SPIN_GRIP={c["grip"]}',f'-DPINBALL_SPIN_FORGET={c["forget"]}',
        '-DPINBALL_SPIN_BENCH=1']

def markdown(r):
    def ci(v):return f"{v['percent']:+.1f}% [{v['ci95'][0]:+.1f}, {v['ci95'][1]:+.1f}]"
    lines=['# Spin experiment','',
        'All nine boards; 60 Hz; paired seeds; two-minute session cap. Every run is repeated byte for byte. '
        'Changes below are relative to the historical seeded-scatter model, labelled current in the saved study. Intervals are 95% seed-cluster bootstrap intervals.', '',
        '| Model | Reactive duration | Reactive score | Reactive coverage | Stalled frames/game | Flipper hits/game | Ramp rides/game | Fixed-input score |',
        '| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |']
    for name,v in r['vs_current'].items():
        p=v['policies']['reactive'];m=p['metrics']
        lines.append(f"| {name} | {ci(p['paired_duration'])} | {ci(p['paired_score'])} | {m['coverage']:.1f}/96 | {m['stalled']:.1f} | {m['flips']:.1f} | {m['ramps']:.1f} | {ci(v['policies']['fixed']['paired_score'])} |")
    lines+=['','## Per-board reactive results','',
        '| Board | Light spin duration | Light spin score | Spin duration | Spin score | Hybrid duration | Hybrid score |',
        '| --- | ---: | ---: | ---: | ---: | ---: | ---: |']
    for light,a,b in zip(r['vs_current']['spin_light']['boards'],r['vs_current']['spin']['boards'],r['vs_current']['hybrid']['boards']):
        lines.append(f"| {a['title']} | {ci(light['duration'])} | {ci(light['score'])} | {ci(a['duration'])} | {ci(a['score'])} | {ci(b['duration'])} | {ci(b['score'])} |")
    lines+=['','## Spin history versus friction alone','',
        'The no-memory control clears spin immediately before each contact but retains the same friction impulse formula. '
        'This isolates the effect of carrying rotation between hits from simply slowing sideways movement.', '']
    p=r['history_effect']['policies']['reactive']
    lines.append(f"Spin versus no-memory: duration {ci(p['paired_duration'])}; score {ci(p['paired_score'])}.")
    lines+=['','## Interpretation','',*r['findings'],'','## Reproduce','',
        '```sh','python3 Pinball/tools/benchmark_spin.py --check','```','',
        'The fixed player gets identical complete button tapes. The reactive player follows the ball, '
        'with the same timing policy/seed but different resulting inputs. Duration is capped observed time; '
        'surviving runs are censored. Score and survival are diagnostic proxies, not measurements of human fun. '
        'The bootstrap describes this fixed seed cohort; it does not cover every player or board design.', '',
        'Normal restitution, normal flipper launch, geometry, gravity and scoring remain the same. '
        'Spin is generated by contact slip, persists between hits and decays with an approximately three-second half-life. '
        'This models one rotation axis, not full 3-D rolling. Grip coefficients are experimental choices, '
        'not measured pinball material values. Scripted ramp/cup transport and new serves clear spin.', '',
        'Firmware and Studio now use `spin_light`; the study retains its historical no-spin/scatter control. '
        '`spin_light`, `spin` and `spin_grippy` use friction coefficients '
        '1/16, 1/8 and 1/4 with all scatter removed. `hybrid` uses 1/8 grip with powered/eject scatter retained '
        'and passive scatter removed. `--record-baseline` deliberately replaces the experiment baseline after review.','']
    return '\n'.join(lines)

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--seeds',type=int,default=32);p.add_argument('--seconds',type=int,default=120)
    p.add_argument('--shot-seeds',type=int,default=512)
    p.add_argument('--out',type=Path,default=GAME/'out/spin-benchmark')
    p.add_argument('--baseline',type=Path,default=BASELINE)
    p.add_argument('--sanitize',action='store_true',help='instrument all native game code with UBSan/bounds')
    p.add_argument('--verify-wasm',action='store_true',help='also compare spin and hybrid native traces with WebAssembly')
    mode=p.add_mutually_exclusive_group();mode.add_argument('--check',action='store_true');mode.add_argument('--record-baseline',action='store_true')
    a=p.parse_args()
    if not 2<=a.seeds<=256 or not 10<=a.seconds<=300 or not 16<=a.shot_seeds<=4096:p.error('unsupported workload')
    out=a.out.resolve();out.mkdir(parents=True,exist_ok=True);WORK.mkdir(parents=True,exist_ok=True)
    before=inputs();flags,sources,_=engine_inputs();compiler=os.environ.get('CXX','clang++')
    if a.sanitize:flags+=['-fsanitize=undefined,bounds',f'-fsanitize-ignorelist={GAME}/tools/sanitizer.ignore','-fno-sanitize-recover=all']
    checks=out/'spin-checks'
    subprocess.run([compiler,'-std=c++17','-O2','-fsanitize=undefined,bounds','-fno-sanitize-recover=all',
                    f'-I{GAME}',str(GAME/'tools/wasm/spin_checks.cpp'),'-o',str(checks)],check=True)
    subprocess.run([checks],check=True)
    boards=json.loads((GAME/'boards/tables.json').read_text());paths=[]
    for board in boards:
        path=out/(board['file']+'.pbt');path.write_bytes(encode(board));paths.append(path)
    # Every object sees the same Ball layout. Only Physics.cpp needs model defines.
    objects=[]
    for i,src in enumerate(sources):
        if src.name=='Physics.cpp':continue
        obj=out/f'common-{i}.o';stamp=obj.with_suffix('.sha256');key=digest([before,flags,str(src)])
        if not obj.exists() or not stamp.exists() or stamp.read_text()!=key:
            subprocess.run([compiler,*flags,'-c',str(src),'-o',str(obj)],check=True,cwd=ROOT);stamp.write_text(key)
        objects.append(obj)
    def build(item):
        name,c=item;extra=flags_for(c);obj=out/(name+'.o');probe=out/(name+'-probe.o');exe=out/name
        for src,dest in [(GAME/'Physics.cpp',obj),(GAME/'tools/wasm/scatter_bench.cpp',probe)]:
            subprocess.run([compiler,*flags,*extra,'-c',str(src),'-o',str(dest)],check=True,cwd=ROOT)
        subprocess.run([compiler,*flags,*map(str,objects),str(obj),str(probe),'-o',str(exe)],check=True,cwd=ROOT)
        return exe
    with ThreadPoolExecutor(max_workers=3) as pool:executables=list(pool.map(build,CONFIGS.items()))
    records={};hashes={};compatibility={};telemetry={}
    legacy=json.loads((GAME/'docs/scatter-baseline.json').read_text())
    for (name,c),exe in zip(CONFIGS.items(),executables):
        command=[str(exe),str(a.seeds),str(a.seconds*60),str(a.shot_seeds),*map(str,paths)]
        first=subprocess.check_output(command,cwd=ROOT);second=subprocess.check_output(command,cwd=ROOT)
        if first!=second:raise SystemExit(f'{name}: non-repeatable measurements')
        (out/(name+'.jsonl')).write_bytes(first);hashes[name]=hashlib.sha256(first).hexdigest()
        data=[json.loads(line) for line in first.splitlines()]
        assert data[0]==dict(kind='model',grip=c['grip'],forget=c['forget'])
        spin=[r for r in data if r['kind']=='spin'];games=[r for r in data if r['kind']=='game']
        telemetry[name]=dict(reactive_mean_spin_frames=st.mean(r['frames'] for r in spin if r['policy']=='reactive'),
                            peak_surface_speed_q8=max(r['peak_q8'] for r in spin))
        assert len(spin)==len(games)==len(boards)*a.seeds*2
        if c['grip']==0:assert all(r['frames']==r['peak_q8']==0 for r in spin)
        if not any(c[k] for k in ('passive','powered','eject')):
            # Scale-zero legacy scatter still advances its RNG, but cannot
            # affect kinematics. Spin itself must be independent of the seed.
            groups={}
            for r in data:
                if r['kind']!='shot':continue
                key=(r['powered'],r['vx'],r['speed'],r['kick'])
                samples=[s[:4] for s in r['samples']]
                if key in groups:assert groups[key]==samples,'spin depends on RNG'
                groups[key]=samples
        records[name]=[r for r in data if r['kind'] not in ('model','spin')]
        if name in ('current','no_scatter') and (a.seeds,a.seconds,a.shot_seeds)==(32,120,512):
            raw=b''.join(line+b'\n' for line in first.splitlines() if json.loads(line)['kind'] not in ('model','spin'))
            compatibility[name]=hashlib.sha256(raw).hexdigest()==legacy['raw_sha256']['current' if name=='current' else 'off']
        print(f'{name}: {len(games)} games; exact repeat passed',flush=True)
    wasm={}
    if a.verify_wasm:
        emxx=Path(os.environ.get('EMXX',str(SDK/'upstream/emscripten/em++')))
        version=subprocess.check_output([emxx,'--version'],text=True)
        if not re.search(r'\b'+re.escape(VERSION)+r'\b',version):raise SystemExit('Use pinned Emscripten '+VERSION)
        wasmflags,_,_=engine_inputs()
        for name in ('spin','hybrid'):
            module=out/(name+'-wasm.cjs')
            subprocess.run([emxx,*wasmflags,*flags_for(CONFIGS[name]),*sources,GAME/'tools/wasm/scatter_bench.cpp',
                '-sENVIRONMENT=node','-sNODERAWFS=1','-sWASM_ASYNC_COMPILATION=0','-o',module],check=True,cwd=ROOT)
            # Full board geometry, contacts, spin history and reactive inputs;
            # the browser and native engine must make identical decisions.
            args=['4','1800','16',*map(str,paths)]
            native=subprocess.check_output([out/name,*args],cwd=ROOT)
            web=subprocess.check_output([node(),module,*args],cwd=ROOT)
            if native!=web:raise SystemExit(f'{name}: native/WASM spin discrepancy')
            wasm[name]=dict(passed=True,games=4*2*len(boards),seconds=30,sha256=hashlib.sha256(web).hexdigest())
            print(f'{name}: native/WASM spin traces identical',flush=True)
    if before!=inputs():raise SystemExit('Sources changed during experiment; rerun.')
    results=analyse(records,boards,'current',scatter_invariants=False)
    vs_off=analyse(records,boards,'no_scatter',scatter_invariants=False)
    history=analyse({k:records[k] for k in ('spin_no_memory','spin')},boards,'spin_no_memory',scatter_invariants=False)['spin']
    findings=[]
    def ci(v):return f"{v['percent']:+.1f}% (95% CI {v['ci95'][0]:+.1f} to {v['ci95'][1]:+.1f}%)"
    for name in ('spin_light','spin','spin_grippy','hybrid'):
        r=results[name]['policies']['reactive']
        findings.append(f"{name}: reactive duration {ci(r['paired_duration'])}; score {ci(r['paired_score'])} versus current.")
    for name in ('spin_light','spin','hybrid'):
        for b in results[name]['boards']:
            if b['duration']['percent'] < -15 or b['score']['percent'] < -20:
                findings.append(f"Review {name} on {b['title']}: duration {ci(b['duration'])}; score {ci(b['score'])}.")
    # Scores have different scales across boards; expose aggregate domination
    # instead of letting one lucrative scoring route masquerade as general fun.
    leave_one_out={}
    ref={(r['board'],r['seed'],r['policy']):r for r in records['current'] if r['kind']=='game'}
    for name in ('spin_light','spin','spin_grippy','hybrid'):
        rows=[r for r in records[name] if r['kind']=='game' and r['policy']=='reactive']
        leave_one_out[name]={}
        for b in boards:
            subset=[r for r in rows if r['board']!=b['id']]
            numerator=sum(r['score'] for r in subset)
            denominator=sum(ref[r['board'],r['seed'],r['policy']]['score'] for r in subset)
            leave_one_out[name][b['title']]=round((numerator/denominator-1)*100,3) if denominator else None
    smallest=min(leave_one_out['spin_light'].items(),key=lambda pair:pair[1])
    findings.append(f"Light spin's aggregate score result is sensitive to board weighting: excluding {smallest[0]}, its reactive score change is {smallest[1]:+.1f}% (descriptive sensitivity check).")
    findings.append('The original current and no-scatter baselines are unchanged.' if compatibility and all(compatibility.values()) else
                    'Original baseline measurements differ; review baseline_compatibility.' if compatibility else
                    'Reduced workload: full original-baseline compatibility was not checked.')
    report=dict(schema=1,workload=dict(seeds=a.seeds,seconds=a.seconds,shot_seeds=a.shot_seeds,
        board_hash=digest(boards),seed_stream='0xA11CE517',bootstrap_seed=0xB0057,bootstrap_replicates=2000),
        configs=CONFIGS,source_hash=digest(before),raw_sha256=hashes,baseline_compatibility=compatibility,
        telemetry=telemetry,vs_current=results,vs_no_scatter=vs_off,history_effect=history,findings=findings,
        leave_one_board_out_score_percent=leave_one_out,
        native_sanitizers=a.sanitize,wasm_verification=wasm,
        compiler=subprocess.check_output([compiler,'--version'],text=True).splitlines()[0])
    baseline=json.loads(a.baseline.read_text()) if a.baseline.exists() else None
    report['matches_baseline']=bool(baseline and baseline['workload']==report['workload'] and baseline['configs']==CONFIGS and baseline['raw_sha256']==hashes)
    (out/'report.json').write_text(json.dumps(report,indent=2)+'\n');(out/'report.md').write_text(markdown(report))
    print('\n'.join(findings));print(out/'report.md')
    if a.record_baseline:a.baseline.write_text(json.dumps(report,indent=2)+'\n')
    elif a.check and not report['matches_baseline']:raise SystemExit('Spin measurements changed: review report before recording a baseline.')

if __name__=='__main__':main()
